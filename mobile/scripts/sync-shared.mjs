/**
 * Copies the web app's shared domain types and option lists into the mobile
 * app so both use exactly the same values. Run after changing them:
 *   npm run sync-shared   (from mobile/)
 * A root unit test (tests/unit/mobile-shared.test.ts) fails if the copies drift.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const out = path.resolve(here, "../src/shared");

export const SHARED_FILES = [
  { from: "types/domain.ts", to: "domain.ts" },
  { from: "lib/constants.ts", to: "constants.ts" },
  { from: "lib/pins/design.ts", to: "design.ts" },
];

export function transform(source) {
  const header = "// GENERATED by mobile/scripts/sync-shared.mjs from the web app. Do not edit.\n";
  return header + source.replace(/from "@\/types\/domain"/g, 'from "./domain"').replace(/from "@\/lib\/constants"/g, 'from "./constants"');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const f of SHARED_FILES) {
    writeFileSync(path.join(out, f.to), transform(readFileSync(path.join(root, f.from), "utf8")));
    console.log(`synced ${f.from} -> src/shared/${f.to}`);
  }
}
